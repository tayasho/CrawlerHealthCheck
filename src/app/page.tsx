'use client';

import { useSession } from 'next-auth/react';
import { useRouter } from 'next/navigation';
import { useEffect } from 'react';

export default function Home() {
  const { data: session, status } = useSession();
  const router = useRouter();

  useEffect(() => {
    if (status === 'unauthenticated') {
      router.push('/login');
    }
  }, [status, router]);

  if (status === 'loading') {
    return (
      <div style={{
        display: 'flex',
        alignItems: 'center',
        justifyContent: 'center',
        height: '100vh',
        background: '#F5F0E8',
        fontFamily: 'Space Grotesk, sans-serif',
        fontSize: '18px',
        fontWeight: 600,
      }}>
        読み込み中...
      </div>
    );
  }

  if (!session) return null;

  return (
    <iframe
      src="/api/dashboard"
      style={{
        position: 'fixed',
        top: 0,
        left: 0,
        width: '100vw',
        height: '100vh',
        border: 'none',
      }}
      title="Crawler Health Check Dashboard"
    />
  );
}
